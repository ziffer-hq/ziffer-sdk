// ACP-392: the onboarding corpus, and the refusal names this product emits.
//
// Same argument as everything above, one directory wider. `search_docs` reads
// EVERY customer-facing onboarding document, and `explain_refusal` reads the
// refusal table inside one of them; both run from a tarball under `npx`, where
// there is no `docs/` beside the module and no repository root to walk up to.
//
// TWO THINGS ARE WALKED RATHER THAN LISTED, and both were listed first in the
// drafting of this slice:
//
//   * the DOCUMENTS. `docs/onboarding/*.md` is read from the directory, so a
//     document added there is served without this file being edited. What IS
//     written here is the opposite -- the documents deliberately NOT served --
//     because a published npm package is the wrong place to discover that a
//     directory gained an internal artifact. The exclusion is pinned BY NAME
//     with its reason, and a pin naming a file that is no longer there HALTS
//     the build: a pin that has stopped firing is a claim nobody is checking
//     (ACP-299's rule).
//   * the REFUSAL NAMES. They are read out of the Rust that emits them -- the
//     gateway's `error_name` module and the Policy Engine's `clause` module
//     and attestation refusals -- and a source that yields NONE halts the
//     build. `explain_refusal` can then say "this is a real name we emit and
//     the support table has no row for it" rather than guessing, and
//     `refusals.test.ts` derives the same set independently off disk.

const ONBOARDING_DIR = join('docs', 'onboarding');

/**
 * The documents under `docs/onboarding/` that are NOT served, by filename,
 * each with the reason it is withheld.
 *
 * THE REASON IS WRITTEN ONCE, in the entry's value, and nowhere else in prose:
 * `docs.test.ts` asserts that `packages/mcp/README.md` neither names a withheld
 * document nor quotes its reason. `search_docs` answers into a customer's coding
 * agent, which is why build state stays out of it for as long as the package is
 * installed -- and why the pin, not a deleted file, is the switch.
 *
 * THE VALUE IS COMPILED INTO THE PUBLISHED PACKAGE (dist/generated/docs-source.js),
 * so it is customer text: it says what the document is, states no gap, and names
 * no ticket and no path of this repository. What the maintainers need stays in
 * this comment: the journey sheet is the team's working record of the onboarding
 * build, and the pin is reversible -- delete the entry and the next build serves
 * the document.
 */
const ONBOARDING_NOT_SERVED = {
  'journey-sheet-2026-09-15.md':
    'withheld: a working record kept by the team that runs ZIFFER, not a guide. ' +
    "It answers no question a developer asks while integrating.",
};

/** Every `*.md` in `docs/onboarding/`, sorted, minus the withheld ones. */
function onboardingDocs() {
  const dir = join(repoRoot, ONBOARDING_DIR);
  let entries;
  try {
    entries = readdirSync(dir).sort();
  } catch (error) {
    fail(
      `OnboardingDirUnreadable: ${ONBOARDING_DIR}: ${error instanceof Error ? error.message : String(error)}\n` +
        '  search_docs serves this directory; without it the tool would answer every question\n' +
        '  with nothing, which reads as an answer.',
    );
    return [];
  }
  const markdown = entries.filter((name) => name.endsWith('.md'));
  for (const withheld of Object.keys(ONBOARDING_NOT_SERVED)) {
    if (!markdown.includes(withheld)) {
      fail(
        `WithheldDocumentAbsent: ${ONBOARDING_DIR}/${withheld} is pinned as not-served and is not there.\n` +
          '  A pin that has stopped firing is a claim nobody is checking. Either the file moved and\n' +
          '  the pin moves with it, or it is gone and the entry goes from ONBOARDING_NOT_SERVED.',
      );
    }
  }
  const served = markdown.filter((name) => !(name in ONBOARDING_NOT_SERVED));
  if (served.length === 0) {
    fail(`OnboardingDirEmpty: ${ONBOARDING_DIR} yielded no document to serve.`);
  }
  return served.map((name) => {
    const relative = `${ONBOARDING_DIR}/${name}`.split('\\').join('/');
    const text = readSource(relative);
    if (text.trim() === '') {
      fail(`OnboardingDocEmpty: ${relative} is empty, so search_docs would rank nothing from it.`);
    }
    return { path: relative, markdown: text };
  });
}

/** `docs/onboarding/support.md` and the marker that opens its refusal table.
 *
 * The marker is the document saying "the table below is the one a checker
 * reads", in its own bytes; `tools/check-support-doc.py` reads the same one.
 * It is a MARKER and not a heading for `guide.ts`'s reason -- renaming a
 * heading is an editorial act that should not silently change what a tool
 * returns. */
const SUPPORT_DOC = `${ONBOARDING_DIR}/support.md`.split('\\').join('/');
const REFUSAL_TABLE_MARKER = '<!-- support:refusal-table -->';

/**
 * Where refusal names are MINTED, and how to read each one out.
 *
 * Read rather than transcribed, `FAILURE_KEYS`'s rule one tool over: a list of
 * refusal names typed into TypeScript agrees with the services on the day it
 * is written. A source that yields no name at all halts the build, because an
 * empty emitter set makes every completeness comparison downstream pass by
 * having nothing to compare.
 */
const REFUSAL_EMITTERS = [
  {
    path: 'services/gateway/src/gateway.rs',
    origin: 'the ZIFFER API',
    what: 'the names the public API answers with, under `pub mod error_name`',
    // `pub const NAME: &str = "Spelling";` inside `pub mod error_name { ... }`.
    read: (text) => constsInModule(text, 'error_name'),
  },
  {
    path: 'services/policy/src/engine.rs',
    origin: 'the Policy Engine',
    what: 'the rules the Policy Engine decides under, which the console and your audit chain name',
    read: (text) => constsInModule(text, 'clause'),
  },
  {
    path: 'services/policy/src/attest.rs',
    origin: 'the Policy Engine, on an approval',
    what: 'the clause ids an attestation is refused under',
    // `clause: "AT-5",` -- a struct field rather than a constant, so it is
    // read as one instead of being folded into the rule above.
    read: (text) => [...text.matchAll(/^\s*clause: "([^"]+)",$/gm)].map((m) => m[1]),
  },
  {
    path: 'services/policy/src/category.rs',
    origin: 'the decision API',
    what: "the refusal categories a decision's `refusal_category` carries",
    read: (text) => constsInModule(text, 'name'),
  },
];

/** Every `pub const X: &str = "value";` inside `pub mod <name> { ... }`.
 *
 * The module is found by its header and closed by the first line that is `}`
 * at the header's own indentation -- the two modules read here are top level
 * and hold only constants, and a nested `mod` inside one would end the span
 * early rather than absorb it. A module that is not there yields nothing,
 * which is what the empty check below turns into a halt. */
function constsInModule(text, name) {
  const lines = text.split('\n');
  const open = lines.findIndex((line) => line.trimEnd() === `pub mod ${name} {`);
  if (open === -1) return [];
  const out = [];
  for (let i = open + 1; i < lines.length; i += 1) {
    if (lines[i] === '}') break;
    const match = /^\s*pub const [A-Z0-9_]+: &str = "([^"]+)";$/.exec(lines[i]);
    if (match !== null) out.push(match[1]);
  }
  return out;
}

