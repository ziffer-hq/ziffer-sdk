// --- the wire Proposal schema ---------------------------------------------
//
// WALKED FROM ONE ENTRY POINT, never listed. `lint_proposal` validates against
// `wire/proposal.schema.json`, which `$ref`s into three other vendored schemas;
// a typed list of four filenames here would be right until a `$ref` moved. The
// closure below follows the refs the schema actually has and HALTS on one that
// resolves to nothing, which is the case a list could not have seen at all.

const SCHEMA_ROOT = join('services', 'validator', 'schemas');
const PROPOSAL_SCHEMA = 'wire/proposal.schema.json';

function loadSchemas() {
  const root = join(repoRoot, SCHEMA_ROOT);
  const byPath = {};
  const byId = {};
  const walk = (dir, prefix) => {
    let entries;
    try {
      entries = readdirSync(dir).sort();
    } catch (error) {
      fail(`SchemaSourceUnreadable: ${dir}: ${error instanceof Error ? error.message : String(error)}`);
      return;
    }
    for (const entry of entries) {
      const relative = prefix === '' ? entry : `${prefix}/${entry}`;
      const absolute = join(dir, entry);
      if (statSync(absolute).isDirectory()) {
        walk(absolute, relative);
      } else if (entry.endsWith('.schema.json')) {
        let doc;
        try {
          doc = JSON.parse(readFileSync(absolute, 'utf8'));
        } catch (error) {
          fail(`SchemaSourceUnreadable: ${relative}: ${error instanceof Error ? error.message : String(error)}`);
          return;
        }
        byPath[relative] = doc;
        if (typeof doc.$id === 'string') byId[doc.$id] = relative;
      }
    }
  };
  walk(root, '');
  return { byPath, byId };
}

const { byPath: allSchemas, byId: schemaIds } = loadSchemas();
if (allSchemas[PROPOSAL_SCHEMA] === undefined) {
  fail(
    `SchemaSourceUnreadable: ${SCHEMA_ROOT}/${PROPOSAL_SCHEMA} is not there.\n` +
      '  lint_proposal has nothing to validate against without it, and a linter with no schema\n' +
      '  would pass every proposal by having no rule to apply.',
  );
}

/**
 * Walk the REACHABLE schema graph from the Proposal, collecting the documents a
 * `$ref` leaves this one for and the keywords the reachable nodes actually use.
 *
 * SCHEMA-AWARE, and the first draft was not. A walk that treats every object key
 * as a keyword counts `schema_id` and `tenant_id` -- property NAMES -- as
 * constraints, and a walk that follows every `$ref` in a whole document drags in
 * the refs of `$defs` nobody reaches: the first version of this collected 106
 * "keywords" across 8 documents where the reachable answer is 21 across 4. Both
 * numbers would have been asserted against, and the assertion would have been
 * about a graph the linter never visits. So the recursion below descends only
 * through the positions that hold a SCHEMA, and a keyword is a key of one.
 */
function pointer(doc, ref, relative) {
  const [base, fragment] = ref.split('#');
  const target = base === '' ? relative : schemaIds[base];
  if (target === undefined) {
    fail(
      `SchemaRefUnresolvable: ${relative} refs ${ref}, and no schema under ${SCHEMA_ROOT} declares that $id.\n` +
        '  The closure is WALKED from the Proposal schema rather than listed, so an unresolvable\n' +
        '  ref has to stop the build: shipping it would give lint_proposal a rule it cannot apply\n' +
        '  and a field it would report as valid by never having looked at it.',
    );
    return null;
  }
  const targetDoc = base === '' ? doc : allSchemas[target];
  if (targetDoc === undefined) {
    fail(`SchemaSourceUnreadable: ${SCHEMA_ROOT}/${target} is reached by a $ref and is not there.`);
    return null;
  }
  let node = targetDoc;
  for (const part of (fragment ?? '').split('/').filter((p) => p !== '')) {
    if (typeof node !== 'object' || node === null || node[part] === undefined) {
      fail(`SchemaRefUnresolvable: ${relative} refs ${ref}, which points at nothing.`);
      return null;
    }
    node = node[part];
  }
  return { node, doc: targetDoc, relative: target };
}

const closure = {};
const keywords = new Set();
const seen = new Set();

/** One schema node. `relative` is the document it lives in, which is what its
 * own local `$ref`s resolve against. */
function walkSchema(node, doc, relative) {
  if (typeof node !== 'object' || node === null || Array.isArray(node)) return;
  for (const key of Object.keys(node)) keywords.add(key);
  closure[relative] = doc;

  if (typeof node.$ref === 'string') {
    if (seen.has(`${relative}|${node.$ref}`)) return;
    seen.add(`${relative}|${node.$ref}`);
    const resolved = pointer(doc, node.$ref, relative);
    if (resolved !== null) walkSchema(resolved.node, resolved.doc, resolved.relative);
    return;
  }
  for (const key of ['items', 'propertyNames', 'additionalProperties', 'not']) {
    if (typeof node[key] === 'object' && node[key] !== null) walkSchema(node[key], doc, relative);
  }
  for (const key of ['properties', '$defs', 'definitions', 'patternProperties']) {
    const table = node[key];
    if (typeof table === 'object' && table !== null) {
      // A `$defs` TABLE on a node this walk reached is walked whole -- a def
      // nobody refs is still shipped in the embedded document, and a keyword in
      // it is one the linter would meet the day a ref reached it. A `$ref` INTO
      // another document still enters at the one def it names, so this does not
      // drag a whole foreign schema in behind one scalar.
      for (const value of Object.values(table)) walkSchema(value, doc, relative);
    }
  }
  for (const key of ['oneOf', 'anyOf', 'allOf', 'prefixItems']) {
    if (Array.isArray(node[key])) for (const item of node[key]) walkSchema(item, doc, relative);
  }
}

walkSchema(allSchemas[PROPOSAL_SCHEMA], allSchemas[PROPOSAL_SCHEMA], PROPOSAL_SCHEMA);

writeFileSync(
  join(outDir, 'schema-source.ts'),
  '// GENERATED by scripts/embed-guide.mjs from services/validator/schemas. Do not edit.\n' +
    '// The wire Proposal schema and the transitive closure of its $refs, walked.\n' +
    `export const SCHEMA_ROOT = ${JSON.stringify(posix(SCHEMA_ROOT))};\n` +
    `export const PROPOSAL_SCHEMA = ${JSON.stringify(PROPOSAL_SCHEMA)};\n` +
    '// eslint-disable-next-line -- a JSON document is `unknown` to this package; the reader narrows it.\n' +
    `export const SCHEMAS: Readonly<Record<string, unknown>> = ${JSON.stringify(closure)};\n` +
    '/** Every keyword the closure above uses. `proposal-lint.ts` is asserted to implement\n' +
    ' * or deliberately ignore each one, so a schema edit that introduces a keyword the\n' +
    ' * reader does not know is a red test rather than a constraint nobody applied. */\n' +
    `export const SCHEMA_KEYWORDS: readonly string[] = ${JSON.stringify([...keywords].sort())};\n`,
  'utf8',
);

process.stderr.write(
  `embed-guide: ${PACKAGES.python} ${python}, ${client.name} ${client.version}, ` +
    `${startedSpans.length} started spans, ` +
    `${Object.keys(closure).length} schemas, ${keywords.size} keywords\n`,
);

